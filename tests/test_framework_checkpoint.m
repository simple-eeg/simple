function testAllTwentyOneScriptsParseWithCodeAnalyzer(testCase)
sources = read_step_sources(testCase.TestData.repoRoot);
verifyEqual(testCase, height(sources), 21);
messageCount = 0;
for i = 1:height(sources)
    scriptPath = fullfile(testCase.TestData.repoRoot, 'scripts', sources.name(i));
    messages = checkcode(scriptPath, '-id');
    verifyTrue(testCase, isstruct(messages), sources.name(i));
    if ~isempty(messages)
        ids = upper(string({messages.id}));
        parseFlags = contains(ids, 'PARSE') | contains(ids, 'SYNTAX') | ...
            contains(ids, 'SYNER') | contains(ids, 'LEX');
        verifyFalse(testCase, any(parseFlags), ...
            sprintf('%s has Code Analyzer parse diagnostics: %s', ...
            sources.name(i), strjoin(ids(parseFlags), ', ')));
    end
    messageCount = messageCount + numel(messages);
end
fprintf('Code Analyzer parsed all 21 workflow scripts without evaluating them (%d advisory messages).\n', ...
    messageCount);
end

