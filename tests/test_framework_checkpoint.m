function testAllScriptsResolveRootAndBindLoggerBeforeStart(testCase)
sources = read_step_sources(testCase.TestData.repoRoot);
core = any(startsWith(sources.name, ["step_1_", "step_2_", "step_3_", "step_4_"]), 2);
verifyEqual(testCase, sum(core), 14);
for i = 1:height(sources)
    source = sources.source(i);
    name = sources.name(i);
    verifyFalse(testCase, contains(source, 'pipeline_paper'), name);
    verifyTrue(testCase, contains(source, "mfilename('fullpath')"), name);
    verifyFalse(testCase, isempty(regexp(char(source), ...
        '(?m)^clear[^\r\n]*log_command_window[^\r\n]*$', 'once')), name);
    verifyTrue(testCase, contains(source, "which('log_command_window')"), name);
    verifyTrue(testCase, contains(source, 'getCanonicalPath()'), name);
    verifyTrue(testCase, contains(source, "addpath("), name);
    verifyTrue(testCase, contains(source, "'-begin'"), name);
    verifyEqual(testCase, count(source, "log_command_window('start')"), 1, name);
    startPosition = first_position(source, "log_command_window('start')");
    if core(i)
        resolverCall = "resolve_framework_project('" + name + "')";
        verifyLessThan(testCase, first_position(source, resolverCall), startPosition, name);
        resolverBody = extractAfter(source, ...
            'function baseDir = resolve_framework_project(expectedScriptName)');
        verifyEqual(testCase, count(source, ...
            'function baseDir = resolve_framework_project(expectedScriptName)'), 1, name);
        resolverClear = first_position(resolverBody, 'clear log_command_window');
        verifyLessThan(testCase, first_position(resolverBody, ...
            "addpath(scriptsDir, '-begin')"), resolverClear, name);
        verifyLessThan(testCase, first_position(resolverBody, ...
            "addpath(functionsDir, '-begin')"), resolverClear, name);
        verifyLessThan(testCase, resolverClear, ...
            first_position(resolverBody, "which('log_command_window')"), name);
        verifyTrue(testCase, contains(resolverBody, ...
            'SIMPLE:UnableToResolveProjectRoot'), name);
    else
        verifyLessThan(testCase, first_position(source, ...
            'resolve_step5_script_file();'), startPosition, name);
        clearLoggerPosition = last_logger_clear_before(source, startPosition);
        addPositions = strfind(char(source), 'addpath(');
        addPositions = addPositions(addPositions < clearLoggerPosition);
        verifyGreaterThanOrEqual(testCase, numel(addPositions), 2, name);
        whichLoggerPosition = last_position_before(source, ...
            "which('log_command_window')", startPosition);
        verifyLessThan(testCase, clearLoggerPosition, whichLoggerPosition, name);
        verifyLessThan(testCase, whichLoggerPosition, startPosition, name);
    end
end
end

