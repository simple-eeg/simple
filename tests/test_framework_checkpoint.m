function position = first_position(source, needle)
positions = strfind(char(source), char(needle));
assert(~isempty(positions), 'Required source token is absent: %s', needle);
position = positions(1);
end

function position = last_position_before(source, needle, boundary)
positions = strfind(char(source), char(needle));
positions = positions(positions < boundary);
assert(~isempty(positions), 'Required source token is absent before boundary: %s', needle);
position = positions(end);
end

function position = last_logger_clear_before(source, boundary)
