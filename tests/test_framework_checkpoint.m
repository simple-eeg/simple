    '(?m)^clear[^\r\n]*log_command_window[^\r\n]*$', 'start');
positions = positions(positions < boundary);
assert(~isempty(positions), ...
    'Required logger-clear statement is absent before log start.');
position = positions(end);
end

function hash = sha256_file(path)
fid = fopen(path, 'rb');
if fid < 0
    error('SIMPLE:TestHashOpenFailed', 'Unable to open %s for hashing.', path);
end
cleanupFile = onCleanup(@() fclose(fid));
digest = java.security.MessageDigest.getInstance('SHA-256');
while true
    [bytes, nRead] = fread(fid, 1024 * 1024, '*uint8');
    if nRead == 0
        break
    end
    digest.update(reshape(typecast(bytes(:), 'int8'), 1, []));
end
[message, errno] = ferror(fid);
if errno ~= 0 && ~(errno == -4 && feof(fid))
    error('SIMPLE:TestHashReadFailed', ...
        'Unable to hash %s completely (%d: %s).', path, errno, message);
end
hash = lower(string(reshape(dec2hex(typecast(digest.digest(), 'uint8'), 2).', 1, [])));
end

